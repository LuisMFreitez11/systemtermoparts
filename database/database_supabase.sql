-- Esquema PostgreSQL (Supabase) del sistema de inventario TERMO PART (WMS).
-- Equivale al esquema MariaDB definido en database.sql + migracion_mejoras.sql.
-- Ejecutar con: php migracion_supabase.php esquema
-- (o pegando este archivo en el SQL Editor de Supabase).

BEGIN;

-- ---------------------------------------------------------------------------
-- Tipos enumerados
-- ---------------------------------------------------------------------------
DO $$ BEGIN
    CREATE TYPE public.tipo_activo AS ENUM ('CALLE', 'TALLER');
EXCEPTION WHEN duplicate_object THEN NULL; END $$;

DO $$ BEGIN
    CREATE TYPE public.estado_herramienta AS ENUM ('DISPONIBLE', 'ASIGNADA', 'EN REPARACION', 'BAJA');
EXCEPTION WHEN duplicate_object THEN NULL; END $$;

DO $$ BEGIN
    CREATE TYPE public.tipo_movimiento_inventario AS ENUM ('CONSUMO', 'INCREMENTO', 'DEVOLUCION', 'ENTRADA', 'DANADO');
EXCEPTION WHEN duplicate_object THEN NULL; END $$;

DO $$ BEGIN
    CREATE TYPE public.tipo_movimiento_herramienta AS ENUM ('SALIDA', 'ENTRADA');
EXCEPTION WHEN duplicate_object THEN NULL; END $$;

DO $$ BEGIN
    CREATE TYPE public.rol_usuario AS ENUM ('ADMIN', 'USUARIO');
EXCEPTION WHEN duplicate_object THEN NULL; END $$;

-- ---------------------------------------------------------------------------
-- Trigger para actualizar "actualizado_en" (equivalente a ON UPDATE CURRENT_TIMESTAMP)
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.actualizar_marca_tiempo()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.actualizado_en = now();
    RETURN NEW;
END;
$$;

-- ---------------------------------------------------------------------------
-- Productos del almacén
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.productos (
    producto_id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku_codigo             varchar(50) NOT NULL,
    nombre_descripcion     varchar(255) NOT NULL,
    categoria              varchar(50) NOT NULL DEFAULT 'OTROS',
    lote_condicion         varchar(50) NOT NULL DEFAULT 'STOCK',
    unidad_medida          varchar(20) NOT NULL DEFAULT 'PZA',
    stock_actual           numeric(12,3) NOT NULL DEFAULT 0,
    stock_minimo           numeric(12,3) NOT NULL DEFAULT 0,
    toma_fisica_anterior   numeric(12,3) NOT NULL DEFAULT 0,
    stock_consumido        numeric(12,3) NOT NULL DEFAULT 0,
    stock_incrementado     numeric(12,3) NOT NULL DEFAULT 0,
    stock_danado           numeric(12,3) NOT NULL DEFAULT 0,
    creado_en              timestamp(0) NOT NULL DEFAULT now(),
    actualizado_en         timestamp(0) NOT NULL DEFAULT now(),
    CONSTRAINT uq_productos_sku_lote_desc UNIQUE (sku_codigo, lote_condicion, nombre_descripcion)
);

CREATE INDEX IF NOT EXISTS idx_productos_lote ON public.productos (lote_condicion);
CREATE INDEX IF NOT EXISTS idx_productos_nombre ON public.productos (nombre_descripcion);
CREATE INDEX IF NOT EXISTS idx_productos_categoria ON public.productos (categoria);

DROP TRIGGER IF EXISTS trg_productos_actualizado_en ON public.productos;
CREATE TRIGGER trg_productos_actualizado_en
    BEFORE UPDATE ON public.productos
    FOR EACH ROW EXECUTE FUNCTION public.actualizar_marca_tiempo();

-- ---------------------------------------------------------------------------
-- Movimientos de inventario
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.movimientos_inventario (
    movimiento_id  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    producto_id    integer NOT NULL,
    tipo           public.tipo_movimiento_inventario NOT NULL,
    cantidad       numeric(12,3) NOT NULL,
    stock_anterior numeric(12,3) NOT NULL,
    stock_nuevo    numeric(12,3) NOT NULL,
    motivo         varchar(255),
    creado_en      timestamp(0) NOT NULL DEFAULT now(),
    CONSTRAINT fk_movimientos_producto
        FOREIGN KEY (producto_id) REFERENCES public.productos (producto_id)
        ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_movimientos_producto ON public.movimientos_inventario (producto_id);
CREATE INDEX IF NOT EXISTS idx_movimientos_fecha ON public.movimientos_inventario (creado_en);

-- ---------------------------------------------------------------------------
-- Herramientas
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.herramientas (
    herramienta_id    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo            varchar(50) NOT NULL,
    nombre            varchar(255) NOT NULL,
    marca             varchar(100) NOT NULL DEFAULT '',
    modelo            varchar(100) NOT NULL DEFAULT '',
    unidad_medida     varchar(20) NOT NULL DEFAULT 'UNIDAD',
    cantidad          integer NOT NULL DEFAULT 1,
    cantidad_prestada integer NOT NULL DEFAULT 0,
    estado            public.estado_herramienta NOT NULL DEFAULT 'DISPONIBLE',
    ubicacion         varchar(150) NOT NULL DEFAULT '',
    responsable       varchar(150) NOT NULL DEFAULT '',
    observaciones     text,
    creado_en         timestamp(0) NOT NULL DEFAULT now(),
    actualizado_en    timestamp(0) NOT NULL DEFAULT now(),
    CONSTRAINT uq_herramientas_codigo UNIQUE (codigo)
);

CREATE INDEX IF NOT EXISTS idx_herramientas_nombre ON public.herramientas (nombre);
CREATE INDEX IF NOT EXISTS idx_herramientas_estado ON public.herramientas (estado);

DROP TRIGGER IF EXISTS trg_herramientas_actualizado_en ON public.herramientas;
CREATE TRIGGER trg_herramientas_actualizado_en
    BEFORE UPDATE ON public.herramientas
    FOR EACH ROW EXECUTE FUNCTION public.actualizar_marca_tiempo();

-- ---------------------------------------------------------------------------
-- Activos (equipos de calle y taller) y sus materiales
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.activos (
    activo_id      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo           public.tipo_activo NOT NULL DEFAULT 'CALLE',
    fecha_ruta     date,
    activo         varchar(50) NOT NULL,
    modelo         varchar(120) NOT NULL DEFAULT '',
    nro_orden      varchar(50) NOT NULL DEFAULT '',
    numero_reporte varchar(50) NOT NULL DEFAULT '',
    nombre_cliente varchar(255) NOT NULL DEFAULT '',
    reparacion     text,
    creado_en      timestamp(0) NOT NULL DEFAULT now(),
    actualizado_en timestamp(0) NOT NULL DEFAULT now(),
    CONSTRAINT uq_activos_tipo_activo_orden UNIQUE (tipo, activo, nro_orden)
);

CREATE INDEX IF NOT EXISTS idx_activos_fecha ON public.activos (fecha_ruta);
CREATE INDEX IF NOT EXISTS idx_activos_cliente ON public.activos (nombre_cliente);

DROP TRIGGER IF EXISTS trg_activos_actualizado_en ON public.activos;
CREATE TRIGGER trg_activos_actualizado_en
    BEFORE UPDATE ON public.activos
    FOR EACH ROW EXECUTE FUNCTION public.actualizar_marca_tiempo();

CREATE TABLE IF NOT EXISTS public.activo_materiales (
    id                  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    activo_id           integer NOT NULL,
    producto_id         integer NOT NULL,
    cantidad            numeric(12,3) NOT NULL DEFAULT 0,
    cantidad_descontada numeric(12,3) NOT NULL DEFAULT 0,
    creado_en           timestamp(0) NOT NULL DEFAULT now(),
    CONSTRAINT uq_activo_material UNIQUE (activo_id, producto_id),
    CONSTRAINT fk_activo_material_activo
        FOREIGN KEY (activo_id) REFERENCES public.activos (activo_id)
        ON DELETE CASCADE,
    CONSTRAINT fk_activo_material_producto
        FOREIGN KEY (producto_id) REFERENCES public.productos (producto_id)
);

CREATE INDEX IF NOT EXISTS idx_activo_material_producto ON public.activo_materiales (producto_id);

-- ---------------------------------------------------------------------------
-- Usuarios y auditoría
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.usuarios (
    usuario_id      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario         varchar(50) NOT NULL,
    nombre_completo varchar(150) NOT NULL DEFAULT '',
    clave_hash      varchar(255) NOT NULL,
    rol             public.rol_usuario NOT NULL DEFAULT 'USUARIO',
    activo          smallint NOT NULL DEFAULT 1,
    ultimo_acceso   timestamp(0),
    creado_en       timestamp(0) NOT NULL DEFAULT now(),
    CONSTRAINT uq_usuarios_usuario UNIQUE (usuario)
);

CREATE TABLE IF NOT EXISTS public.historial_usuario (
    historial_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id   integer,
    usuario      varchar(50) NOT NULL DEFAULT '',
    accion       varchar(80) NOT NULL,
    detalle      varchar(500) NOT NULL DEFAULT '',
    ip           varchar(45) NOT NULL DEFAULT '',
    creado_en    timestamp(0) NOT NULL DEFAULT now(),
    CONSTRAINT fk_historial_usuario
        FOREIGN KEY (usuario_id) REFERENCES public.usuarios (usuario_id)
        ON DELETE SET NULL
);

CREATE INDEX IF NOT EXISTS idx_historial_usuario ON public.historial_usuario (usuario_id);
CREATE INDEX IF NOT EXISTS idx_historial_fecha ON public.historial_usuario (creado_en);

-- ---------------------------------------------------------------------------
-- Movimientos de herramientas
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.herramientas_movimientos (
    movimiento_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    herramienta_id integer NOT NULL,
    tipo          public.tipo_movimiento_herramienta NOT NULL,
    cantidad      integer NOT NULL,
    fecha         date NOT NULL,
    responsable   varchar(150) NOT NULL DEFAULT '',
    destino       varchar(150) NOT NULL DEFAULT '',
    observaciones text,
    usuario_id    integer,
    creado_en     timestamp(0) NOT NULL DEFAULT now(),
    CONSTRAINT fk_hmov_herramienta
        FOREIGN KEY (herramienta_id) REFERENCES public.herramientas (herramienta_id)
        ON DELETE CASCADE,
    CONSTRAINT fk_hmov_usuario
        FOREIGN KEY (usuario_id) REFERENCES public.usuarios (usuario_id)
        ON DELETE SET NULL
);

CREATE INDEX IF NOT EXISTS idx_hmov_herramienta ON public.herramientas_movimientos (herramienta_id);
CREATE INDEX IF NOT EXISTS idx_hmov_fecha ON public.herramientas_movimientos (fecha);

-- ---------------------------------------------------------------------------
-- Entradas de almacén
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.entradas_almacen (
    entrada_id     integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    producto_id    integer NOT NULL,
    cantidad       numeric(12,3) NOT NULL,
    fecha_entrada  date NOT NULL,
    referencia     varchar(100) NOT NULL DEFAULT '',
    proveedor      varchar(150) NOT NULL DEFAULT '',
    observaciones  text,
    stock_anterior numeric(12,3) NOT NULL,
    stock_nuevo    numeric(12,3) NOT NULL,
    movimiento_id  integer,
    creado_en      timestamp(0) NOT NULL DEFAULT now(),
    CONSTRAINT fk_entradas_producto
        FOREIGN KEY (producto_id) REFERENCES public.productos (producto_id),
    CONSTRAINT fk_entradas_movimiento
        FOREIGN KEY (movimiento_id) REFERENCES public.movimientos_inventario (movimiento_id)
        ON DELETE SET NULL
);

CREATE INDEX IF NOT EXISTS idx_entradas_producto ON public.entradas_almacen (producto_id);
CREATE INDEX IF NOT EXISTS idx_entradas_fecha ON public.entradas_almacen (fecha_entrada);

-- ---------------------------------------------------------------------------
-- Materiales dañados
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.materiales_danados (
    danado_id      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    producto_id    integer NOT NULL,
    cantidad       numeric(12,3) NOT NULL,
    fecha_dano     date NOT NULL,
    motivo         varchar(150) NOT NULL DEFAULT '',
    observaciones  text,
    stock_anterior numeric(12,3) NOT NULL,
    stock_nuevo    numeric(12,3) NOT NULL,
    movimiento_id  integer,
    creado_en      timestamp(0) NOT NULL DEFAULT now(),
    CONSTRAINT fk_danados_producto
        FOREIGN KEY (producto_id) REFERENCES public.productos (producto_id),
    CONSTRAINT fk_danados_movimiento
        FOREIGN KEY (movimiento_id) REFERENCES public.movimientos_inventario (movimiento_id)
        ON DELETE SET NULL
);

CREATE INDEX IF NOT EXISTS idx_danados_producto ON public.materiales_danados (producto_id);
CREATE INDEX IF NOT EXISTS idx_danados_fecha ON public.materiales_danados (fecha_dano);

-- ---------------------------------------------------------------------------
-- Tomas físicas
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.tomas_fisicas (
    toma_id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    registrada_en   timestamp(0) NOT NULL DEFAULT now(),
    total_productos integer NOT NULL DEFAULT 0,
    total_unidades  numeric(14,3) NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS public.toma_fisica_detalle (
    detalle_id  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    toma_id     integer NOT NULL,
    producto_id integer NOT NULL,
    cantidad    numeric(12,3) NOT NULL DEFAULT 0,
    CONSTRAINT fk_toma_detalle_toma
        FOREIGN KEY (toma_id) REFERENCES public.tomas_fisicas (toma_id)
        ON DELETE CASCADE,
    CONSTRAINT fk_toma_detalle_producto
        FOREIGN KEY (producto_id) REFERENCES public.productos (producto_id)
        ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_toma_detalle_toma ON public.toma_fisica_detalle (toma_id);
CREATE INDEX IF NOT EXISTS idx_toma_detalle_producto ON public.toma_fisica_detalle (producto_id);

COMMIT;
